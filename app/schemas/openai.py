import time
import uuid
from enum import StrEnum
from typing import Literal, Optional

from langchain_core.messages import AIMessage, BaseMessage, HumanMessage, SystemMessage
from pydantic import BaseModel, Field


class ChatMessage(BaseModel):
    role: Literal["system", "user", "assistant"] = Field(
        description="The role of the messages author."
    )
    content: str = Field(description="The contents of the message.")


class ChatCompletionRequest(BaseModel):
    model: str = Field(
        default="advanced-rag-agent",
        description="ID of the model to use. Open WebUI sends this automatically.",
    )
    messages: list[ChatMessage] = Field(
        description="A list of messages comprising the conversation so far."
    )
    stream: Optional[bool] = Field(
        default=False, description="If set, partial message deltas will be sent, like in ChatGPT."
    )
    temperature: Optional[float] = Field(
        default=0.0,
        description="Sampling temperature. Handled by the client but ignored by the deterministic RAG.",
    )
    n: Optional[int] = Field(default=1, description="How many completions to generate.")

    def to_langchain_messages(self, drop_system_messages=True) -> list[BaseMessage]:
        """Translates the strict API DTOs into internal LangChain domain objects."""
        internal_messages = []
        for msg in self.messages:
            if msg.role == "user":
                internal_messages.append(HumanMessage(content=msg.content))
            elif msg.role == "assistant":
                internal_messages.append(AIMessage(content=msg.content))
            elif msg.role == "system":
                # Security boundary: optionally ignore frontend system prompts
                if not drop_system_messages:
                    internal_messages.append(SystemMessage(content=msg.content))
        return internal_messages


class ChatChoice(BaseModel):
    index: int = Field(default=0)
    message: ChatMessage = Field(description="The message generated by the RAG model.")
    finish_reason: str = Field(
        default="stop", description="The reason the model stopped generating. Usually 'stop'."
    )


class ChatCompletionResponse(BaseModel):
    id: str = Field(
        default_factory=lambda: f"chatcmpl-{uuid.uuid4().hex}",
        description="A unique identifier for the chat completion.",
    )
    object: Literal["chat.completion"] = Field(
        default="chat.completion", description="The object type, which is always chat.completion."
    )
    created: int = Field(
        default_factory=lambda: int(time.time()),
        description="The Unix timestamp (in seconds) of when the completion was created.",
    )
    model: str = Field(description="The model used for the chat completion.")
    choices: list[ChatChoice] = Field(
        description="A list of chat completion choices. Can be more than one if n > 1."
    )


class ResponseFormat(StrEnum):
    MARKDOWN = "markdown"
    JSON = "json"


class ModelCard(BaseModel):
    id: str
    object: str = "model"
    created: int = Field(default_factory=lambda: int(time.time()))
    owned_by: str = "rag_api"


class ModelList(BaseModel):
    object: str = "list"
    data: list[ModelCard]


class OpenAIError(BaseModel):
    message: str
    type: str
    param: str | None = None
    code: str | None = None


class OpenAIErrorEnvelope(BaseModel):
    error: OpenAIError
